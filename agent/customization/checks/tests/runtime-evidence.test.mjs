import test from 'node:test';
import assert from 'node:assert/strict';
import {homedir,tmpdir} from 'node:os';
import {join} from 'node:path';
import {mkdtempSync,mkdirSync,readFileSync,writeFileSync,statSync,utimesSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
const root=process.env.PI_CODING_AGENT_DIR || join(homedir(),'.pi/agent');
const version=readFileSync(join(root,'install/current-version'),'utf8').trim();
const modules=join(root,'install/releases',version,'node_modules');
const {createJiti}=await import(pathToFileURL(join(modules,'jiti/lib/jiti.mjs')));
const jiti=createJiti(import.meta.url);
const {createRuntimeStatus}=await jiti.import(join(root,'extensions/timrt-suite/runtime-status.ts'));
const {inspectDeletionScripts,SCRIPT_EVIDENCE_LIMIT}=await jiti.import(join(root,'extensions/timrt-suite/guards.ts'));
const {inspectDeletionCall}=await jiti.import(join(root,'extensions/timrt-suite/deletion-review.ts'));
test('loaded build identity stays pinned across source edits, rebuilds and reloads',()=>{
  const dir=mkdtempSync(join(tmpdir(),'pi-runtime-state-'));
  for(const folder of ['extensions/timrt-suite','customization/runtime'])mkdirSync(join(dir,folder),{recursive:true});
  const source='extensions/timrt-suite/permissions.ts',bundle=join(dir,'extensions/timrt-suite/timrt-suite.compiled.mjs');
  writeFileSync(join(dir,source),'original');writeFileSync(bundle,'compiled');
  utimesSync(join(dir,source),1000,1000);utimesSync(bundle,2000,2000);
  const manifest=join(dir,'customization/runtime/compiled-extensions.json');
  const save=buildId=>writeFileSync(manifest,JSON.stringify({buildId,files:{[source]:statSync(join(dir,source)).mtimeMs}}));
  save('build-a');
  const running=createRuntimeStatus(dir,{buildId:'build-a',loadedAt:'2026-10-19T00:00:00Z'});
  assert.equal(running().reloadRequired,false);
  writeFileSync(join(dir,source),'changed');
  assert.equal(running().sourceDirty,true);assert.match(running().warning,/rebuild/);
  utimesSync(bundle,Date.now()/1000+10,Date.now()/1000+10);save('build-b');
  assert.equal(running().sourceDirty,false);assert.equal(running().loadedBuild,'build-a');
  assert.equal(running().diskBuild,'build-b');assert.match(running().warning,/session still needs/);
  assert.equal(createRuntimeStatus(dir,{buildId:'build-b'})().reloadRequired,false);
});
test('script evidence expands only when called, stays bounded and hashes the full program',()=>{
  const dir=mkdtempSync(join(tmpdir(),'pi-script-evidence-'));
  const file=join(dir,'large.mjs'),source='// '+ 'x'.repeat(60000)+'\nconsole.log("safe");\n';
  writeFileSync(file,source);
  const result=inspectDeletionScripts('node ./large.mjs',dir,'powershell');
  assert.equal(result.scripts[0].source,source);assert.equal(result.scripts[0].truncated,false);
  assert.equal(result.opaque,false);assert.equal(result.destructive,false);
  const hash=result.scripts[0].sha256;
  writeFileSync(file,source+'// changed');
  assert.notEqual(inspectDeletionScripts('node ./large.mjs',dir,'powershell').scripts[0].sha256,hash);
  writeFileSync(file,'x'.repeat(SCRIPT_EVIDENCE_LIMIT.perFile+1));
  const bounded=inspectDeletionScripts('node ./large.mjs',dir,'powershell');
  assert.equal(bounded.scripts[0].source.length,SCRIPT_EVIDENCE_LIMIT.perFile);
  assert.equal(bounded.scripts[0].truncated,true);assert.equal(bounded.opaque,true);
  assert.equal(inspectDeletionScripts('Get-Content ./large.mjs',dir,'powershell').scripts.length,0);
});
test('opaque execution is reviewed separately from actual cleanup',()=>{
  const dir=mkdtempSync(join(tmpdir(),'pi-risk-kinds-'));
  assert.equal(inspectDeletionCall('powershell',{command:'pwsh -EncodedCommand Zg=='},dir).kind,'execution');
  assert.equal(inspectDeletionCall('powershell',{command:'Remove-Item -LiteralPath ./cache -Recurse'},dir).kind,'cleanup');
});
